import {loadEnvConfig} from "@next/env";
import {randomUUID} from "node:crypto";
import bcrypt from "bcryptjs";
loadEnvConfig(process.cwd());
const {db}=await import("../lib/db");
const email=(process.env.ADMIN_EMAIL||"adminsr@gmail.com").trim().toLowerCase();
const password=process.env.ADMIN_PASSWORD;
if(!password||password.length<14)throw new Error("Set a new ADMIN_PASSWORD of at least 14 characters in private .env.local.");
const existing=db.prepare("SELECT id FROM users WHERE email=?").get(email) as {id:string}|undefined;
const id=existing?.id||randomUUID();
const hash=await bcrypt.hash(password,12);
if(existing)db.prepare("UPDATE users SET password_hash=?,role='admin',is_blocked=0 WHERE id=?").run(hash,id);
else db.prepare("INSERT INTO users(id,email,username,password_hash,role) VALUES(?,?,?,?, 'admin')").run(id,email,"sr-admin",hash);
db.prepare("INSERT INTO admin_audit_logs(admin_id,action,target_type,target_id,details) VALUES(?,?,?,?,?)").run(id,"admin_provisioned","user",id,JSON.stringify({email}));
console.log("Administrator account is ready:",email,". Remove ADMIN_PASSWORD from the environment.");
